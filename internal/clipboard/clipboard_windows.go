//go:build windows

package clipboard

import (
	"bytes"
	"fmt"
	"runtime"
	"syscall"
	"time"
	"unicode/utf16"
	"unsafe"

	systemclipboard "github.com/atotto/clipboard"
	"golang.org/x/sys/windows"
)

const (
	cfText        = 1
	cfOEMText     = 7
	cfUnicodeText = 13
	cfLocale      = 16
	gmemMoveable  = 0x0002
)

var (
	clipboardUser32 = windows.NewLazySystemDLL("user32.dll")
	clipboardKernel = windows.NewLazySystemDLL("kernel32.dll")

	procOpenClipboard           = clipboardUser32.NewProc("OpenClipboard")
	procCloseClipboard          = clipboardUser32.NewProc("CloseClipboard")
	procEmptyClipboard          = clipboardUser32.NewProc("EmptyClipboard")
	procGetClipboardData        = clipboardUser32.NewProc("GetClipboardData")
	procSetClipboardData        = clipboardUser32.NewProc("SetClipboardData")
	procEnumClipboardFormats    = clipboardUser32.NewProc("EnumClipboardFormats")
	procRegisterClipboardFormat = clipboardUser32.NewProc("RegisterClipboardFormatW")
	procGlobalAlloc             = clipboardKernel.NewProc("GlobalAlloc")
	procGlobalFree              = clipboardKernel.NewProc("GlobalFree")
	procGlobalLock              = clipboardKernel.NewProc("GlobalLock")
	procGlobalUnlock            = clipboardKernel.NewProc("GlobalUnlock")
	procGlobalSize              = clipboardKernel.NewProc("GlobalSize")
)

func newPlatformClipboard() (*Clipboard, error) {
	return &Clipboard{
		getFunc:      systemclipboard.ReadAll,
		setFunc:      systemclipboard.WriteAll,
		snapshotFunc: windowsSnapshot,
		restoreFunc:  windowsRestoreIfUnchanged,
	}, nil
}

func windowsSnapshot() (Snapshot, error) {
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	if err := openWindowsClipboard(); err != nil {
		return Snapshot{Reason: "snapshot_open_failed"}, err
	}
	defer closeWindowsClipboard()

	htmlFormat, err := windowsClipboardFormat("HTML Format")
	if err != nil {
		return Snapshot{Reason: "format_register_failed"}, err
	}
	pngFormat, err := windowsClipboardFormat("PNG")
	if err != nil {
		return Snapshot{Reason: "format_register_failed"}, err
	}

	var formats []FormatData
	for current := uintptr(0); ; {
		next, _, callErr := procEnumClipboardFormats.Call(current)
		if next == 0 {
			if callErr != syscall.Errno(0) {
				return Snapshot{Reason: "format_list_failed"}, callErr
			}
			break
		}
		current = next
		switch uint32(current) {
		case cfUnicodeText:
			data, err := windowsTextData()
			if err != nil {
				return Snapshot{Reason: "snapshot_read_failed"}, err
			}
			formats = append(formats, FormatData{Format: FormatText, Data: data})
		case uint32(htmlFormat):
			data, err := windowsClipboardBytes(current)
			if err != nil {
				return Snapshot{Reason: "snapshot_read_failed"}, err
			}
			formats = append(formats, FormatData{Format: FormatHTML, Data: data})
		case uint32(pngFormat):
			data, err := windowsClipboardBytes(current)
			if err != nil {
				return Snapshot{Reason: "snapshot_read_failed"}, err
			}
			formats = append(formats, FormatData{Format: FormatPNG, Data: data})
		case cfText, cfOEMText, cfLocale:
			// Text aliases and CF_LOCALE are regenerated by Windows from CF_UNICODETEXT.
		default:
			return Snapshot{Reason: "unsupported_format"}, nil
		}
	}
	if len(formats) == 0 {
		return Snapshot{Reason: "empty_or_unknown_clipboard"}, nil
	}
	var total int
	for _, format := range formats {
		total += len(format.Data)
	}
	if total > maxSnapshotBytes {
		return Snapshot{Reason: "snapshot_too_large"}, nil
	}
	return Snapshot{Formats: formats, Restorable: true}, nil
}

func windowsRestoreIfUnchanged(snapshot Snapshot, temporaryText string) (RestoreResult, error) {
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	if err := openWindowsClipboard(); err != nil {
		return RestoreResult{Reason: "clipboard_changed"}, nil
	}
	defer closeWindowsClipboard()

	current, err := windowsTextData()
	if err != nil || !bytes.Equal(current, []byte(temporaryText)) {
		return RestoreResult{Reason: "clipboard_changed"}, nil
	}

	htmlFormat, err := windowsClipboardFormat("HTML Format")
	if err != nil {
		return RestoreResult{Reason: "format_register_failed"}, err
	}
	pngFormat, err := windowsClipboardFormat("PNG")
	if err != nil {
		return RestoreResult{Reason: "format_register_failed"}, err
	}

	type pendingFormat struct {
		format uintptr
		handle uintptr
	}
	pending := make([]pendingFormat, 0, len(snapshot.Formats))
	for _, format := range snapshot.Formats {
		clipboardFormat := uintptr(cfUnicodeText)
		data := format.Data
		switch format.Format {
		case FormatText:
			data = utf16Bytes(string(format.Data))
		case FormatHTML:
			clipboardFormat = htmlFormat
		case FormatPNG:
			clipboardFormat = pngFormat
		default:
			return RestoreResult{Reason: "unsupported_format"}, nil
		}
		handle, err := windowsGlobalMemory(data)
		if err != nil {
			for _, allocated := range pending {
				_, _, _ = procGlobalFree.Call(allocated.handle)
			}
			return RestoreResult{Reason: "restore_write_failed"}, err
		}
		pending = append(pending, pendingFormat{format: clipboardFormat, handle: handle})
	}

	if ok, _, err := procEmptyClipboard.Call(); ok == 0 {
		for _, allocated := range pending {
			_, _, _ = procGlobalFree.Call(allocated.handle)
		}
		return RestoreResult{Reason: "restore_write_failed"}, err
	}
	for i := range pending {
		if ok, _, err := procSetClipboardData.Call(pending[i].format, pending[i].handle); ok == 0 {
			for _, remaining := range pending[i:] {
				_, _, _ = procGlobalFree.Call(remaining.handle)
			}
			return RestoreResult{Reason: "restore_write_failed"}, err
		}
		pending[i].handle = 0
	}
	return RestoreResult{Restored: true}, nil
}

func openWindowsClipboard() error {
	deadline := time.Now().Add(time.Second)
	for time.Now().Before(deadline) {
		if ok, _, _ := procOpenClipboard.Call(0); ok != 0 {
			return nil
		}
		time.Sleep(time.Millisecond)
	}
	return fmt.Errorf("OpenClipboard timed out")
}

func closeWindowsClipboard() {
	_, _, _ = procCloseClipboard.Call()
}

func windowsClipboardFormat(name string) (uintptr, error) {
	wide, err := windows.UTF16PtrFromString(name)
	if err != nil {
		return 0, err
	}
	format, _, err := procRegisterClipboardFormat.Call(uintptr(unsafe.Pointer(wide)))
	if format == 0 {
		return 0, err
	}
	return format, nil
}

func windowsTextData() ([]byte, error) {
	handle, _, err := procGetClipboardData.Call(cfUnicodeText)
	if handle == 0 {
		return nil, err
	}
	data, err := windowsClipboardBytes(handle)
	if err != nil {
		return nil, err
	}
	if len(data)%2 != 0 {
		return nil, fmt.Errorf("invalid UTF-16 clipboard data")
	}
	chars := unsafe.Slice((*uint16)(unsafe.Pointer(&data[0])), len(data)/2)
	for i, char := range chars {
		if char == 0 {
			chars = chars[:i]
			break
		}
	}
	return []byte(string(utf16.Decode(chars))), nil
}

func windowsClipboardBytes(handle uintptr) ([]byte, error) {
	size, _, err := procGlobalSize.Call(handle)
	if size == 0 {
		return nil, err
	}
	if size > maxSnapshotBytes+2 {
		return nil, fmt.Errorf("clipboard data exceeds snapshot limit")
	}
	ptr, _, err := procGlobalLock.Call(handle)
	if ptr == 0 {
		return nil, err
	}
	defer procGlobalUnlock.Call(handle)
	return append([]byte(nil), unsafe.Slice((*byte)(unsafe.Pointer(ptr)), int(size))...), nil
}

func windowsGlobalMemory(data []byte) (uintptr, error) {
	if len(data) == 0 {
		data = []byte{0}
	}
	handle, _, err := procGlobalAlloc.Call(gmemMoveable, uintptr(len(data)))
	if handle == 0 {
		return 0, err
	}
	ptr, _, err := procGlobalLock.Call(handle)
	if ptr == 0 {
		_, _, _ = procGlobalFree.Call(handle)
		return 0, err
	}
	copy(unsafe.Slice((*byte)(unsafe.Pointer(ptr)), len(data)), data)
	_, _, _ = procGlobalUnlock.Call(handle)
	return handle, nil
}

func utf16Bytes(text string) []byte {
	chars := append(utf16.Encode([]rune(text)), 0)
	return unsafe.Slice((*byte)(unsafe.Pointer(&chars[0])), len(chars)*2)
}
